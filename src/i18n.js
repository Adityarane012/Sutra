export const cls = (lang, grade) => (lang === 'hi' ? `कक्षा ${grade}` : `Class ${grade}`);

export function t(lang, key) {
  if (lang === 'hinglish') return S[key]?.hinglish ?? S[key]?.en ?? key;
  return S[key]?.[lang] ?? S[key]?.en ?? key;
}

/** Content fields are either a string or { en, hi, hinglish }. */
export function tx(value, lang) {
  if (value == null) return '';
  if (typeof value === 'string') return value;
  if (lang === 'hinglish') return value.hinglish ?? value.en ?? value.hi;
  return value[lang] ?? value.en;
}
